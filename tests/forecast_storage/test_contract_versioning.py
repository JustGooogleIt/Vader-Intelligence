"""Record-contract versioning against archives written by OLDER implementations (D-001).

The SQL fixtures under tests/fixtures/legacy_archives were generated by running the
older code itself (generate.py, see its README): main ebb58df (schema 3, contract 1),
the PR #11 head 5811991 (contract 2 as written before the PR #12 amendment, including
the review's adversarial records) and the PR #16 head 82665cd (contract 2 as amended).
All are synthetic. These tests prove that the current code opens, verifies, backs up and
migrates every one of them without reinterpreting a legacy row as operational proof.
"""

import json
import sqlite3
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

from ops import archive as ops_archive
from vader_intelligence.cli import execute, parser
from vader_intelligence.evaluation.service import evaluate
from vader_intelligence.forecast import evidence, journal, schema
from vader_intelligence.forecast.research import Protocol
from vader_intelligence.forecast.witness import witness
from vader_intelligence.storage import Store, writer_lock

from .fixtures import connect, snapshot

LEGACY = Path(__file__).resolve().parents[1] / "fixtures/legacy_archives"
sys.path.insert(0, str(LEGACY))
from generate import load  # noqa: E402

ARCHIVES = {
    "main": "main-ebb58df-schema3.sql",
    "draft": "draft-5811991-schema4.sql",
    "amended": "amended-82665cd-schema4.sql",
}
# Expected per-era facts, read from the archives the older code wrote.
SCHEMA = {"main": 3, "draft": 4, "amended": 4}
LEGACY_ROWS = {"main": 0, "draft": 25, "amended": 0}
# Every current-rule failure of a draft row is one of the PR #12 amendments.
DRAFT_REASONS = {
    "reference provenance mismatch",
    "contract-2 receipt requires the operational witness run that observed it",
}


def materialize(era, tmp_path):
    path = tmp_path / f"{era}.sqlite3"
    load(LEGACY / ARCHIVES[era], path)
    return path


def proof_receipts(db):
    """Receipt ids the shared operational-proof predicate admits, in each row's own
    namespace (the predicate's one parameter)."""
    return [
        row[0]
        for row in db.execute(
            "SELECT r.id FROM forecast_receipts r WHERE"
            + evidence.PROOF.replace(
                "=?", "=json_extract(r.payload_json,'$.observer_namespace')", 1
            )
            + " ORDER BY r.id"
        )
    ]


def cli(path, *args):
    return execute(parser().parse_args(["--db", str(path), *args]))


@pytest.mark.parametrize("era", sorted(ARCHIVES))
def test_legacy_archive_opens_verifies_and_classifies(era, tmp_path):
    path = materialize(era, tmp_path)
    store = Store(path, min_free_bytes=0, readonly=True)
    try:
        assert store.schema_version() == SCHEMA[era]
        assert store.verify_integrity() == []
        result = journal.integrity(store.db)
    finally:
        store.close()
    assert result["integrity"] == "verified"
    assert result["legacy_rows"] == LEGACY_ROWS[era]
    assert result["admissibility"] == ("legacy_rows_present" if LEGACY_ROWS[era] else "current")
    assert result["record_contracts"]["forecast_receipts"]["3"] == 0  # no contract 3 yet
    for example in result["legacy_examples"]:
        assert example["contract"] in (1, 2) and example["reason"] in DRAFT_REASONS


def test_draft_rows_fail_exactly_the_amended_rules_and_pass_the_frozen_ones(tmp_path):
    """The rules="draft" path reproduces what 5811991 accepted, row by row, and the
    current rules reject each such row for one of the PR #12 amendments only."""
    path = materialize("draft", tmp_path)
    db = sqlite3.connect(path)
    try:
        seen = 0
        for table in schema.COLUMNS:
            for (payload_json,) in db.execute(f"SELECT payload_json FROM {table}"):
                payload = json.loads(payload_json)
                journal.validate_links(db, table, payload, rules="draft")  # never raises
                label, reason = journal.classify_with_reason(db, table, payload)
                if label == "legacy_draft":
                    seen += 1
                    assert reason in DRAFT_REASONS
        assert seen == LEGACY_ROWS["draft"]
    finally:
        db.close()


def test_nothing_in_the_draft_archive_is_operational_proof(tmp_path):
    path = materialize("draft", tmp_path)
    db = sqlite3.connect(path)
    try:
        # The archive holds forward_shadow receipts a PR #11 witness wrote for synthetic
        # (injected-transport) fetches, a supplied receipt, and synthetic draft receipts.
        modes = dict(
            db.execute(
                "SELECT json_extract(payload_json,'$.mode'), COUNT(*) FROM forecast_receipts"
                " GROUP BY 1"
            ).fetchall()
        )
        assert modes == {"forward_shadow": 10, "synthetic": 12}
        assert proof_receipts(db) == []
        later = datetime(2030, 1, 1, tzinfo=timezone.utc)
        for (fetch_id,) in db.execute("SELECT id FROM fetches"):
            for mode in ("forward_shadow", "synthetic"):
                assert evidence.fetch_availability(db, fetch_id, mode=mode).status != "witnessed"
        for mode in ("forward_shadow", "synthetic"):
            assert evidence.discovery_as_of(db, later, mode=mode).kind is None
    finally:
        db.close()


@pytest.mark.parametrize("era", sorted(ARCHIVES))
def test_migration_to_contract_three_preserves_every_row_and_classification(era, tmp_path):
    path = materialize(era, tmp_path)
    db = sqlite3.connect(path)
    before = snapshot(db)
    classified = journal.integrity(db)
    db.close()
    result = cli(path, "forecast", "migrate", "--record-contract", "3")
    assert result["schema_version"] == 5 and result["record_contract"] == 3 and result["migrated"]
    db = sqlite3.connect(path)
    try:
        after = snapshot(db)
        assert [r[0] for r in after["schema_migrations"]] == [1, 2, 3, 4, 5]
        assert all(after[t] == rows for t, rows in before.items() if t != "schema_migrations")
        again = journal.integrity(db)
        for key in ("record_contracts", "classification", "legacy_rows", "legacy_evaluations"):
            assert again[key] == classified[key]
    finally:
        db.close()
    assert cli(path, "forecast", "migrate", "--record-contract", "3")["migrated"] is False


@pytest.mark.parametrize("era", ["draft", "amended"])
def test_backup_and_restore_preserve_legacy_rows_and_classification(era, tmp_path):
    path = materialize(era, tmp_path)
    cli(path, "forecast", "migrate", "--record-contract", "3")
    db = sqlite3.connect(path)
    before, classified = snapshot(db), journal.integrity(db)
    db.close()
    backup, restored = tmp_path / "backup.sqlite3", tmp_path / "restored.sqlite3"
    assert ops_archive.backup(path, backup)["schema_version"] == 5
    assert ops_archive.backup(backup, restored)["schema_version"] == 5
    db = sqlite3.connect(restored)
    try:
        assert snapshot(db) == before
        assert journal.integrity(db)["classification"] == classified["classification"]
    finally:
        db.close()


def test_amended_contract_two_receipts_stay_proof_and_are_not_rewitnessed(tmp_path):
    path = materialize("amended", tmp_path)
    db = sqlite3.connect(path)
    proven = proof_receipts(db)
    db.close()
    assert len(proven) == 12  # the PR #16 witness recorded lineage, namespace and session
    cli(path, "forecast", "migrate", "--record-contract", "3")
    with writer_lock(path):
        store = Store(path, min_free_bytes=0)
        try:
            moment = datetime(2026, 9, 28, 1, 0, tzinfo=timezone.utc)
            result = witness(store, clock=lambda: moment, monotonic=lambda: 0.0)
            assert result["status"] in ("complete", "partial")
            db = store.db
            assert proof_receipts(db)[: len(proven)] == proven
            # No subject that already had operational proof receives a second receipt.
            for column in ("fetch_id", "discovery_id", "binding_id", "publication_id"):
                duplicated = db.execute(
                    f"SELECT {column}, COUNT(*) FROM forecast_receipts WHERE {column} IS NOT NULL"
                    f" GROUP BY {column} HAVING COUNT(*) > 1"
                ).fetchall()
                assert duplicated == [], column
            assert journal.integrity(db)["legacy_rows"] == 0
        finally:
            store.close()


def test_draft_subjects_are_witnessed_again_under_contract_three_at_the_real_time(tmp_path):
    path = materialize("draft", tmp_path)
    cli(path, "forecast", "migrate", "--record-contract", "3")
    moment = datetime(2026, 9, 29, 12, 0, tzinfo=timezone.utc)
    with writer_lock(path):
        store = Store(path, min_free_bytes=0)
        try:
            result = witness(store, clock=lambda: moment, monotonic=lambda: 0.0, max_subjects=500)
            assert result["receipts"] > 0
            db = store.db
            new = db.execute(
                "SELECT json_extract(payload_json,'$.mode'), observed_at FROM forecast_receipts"
                " WHERE json_extract(payload_json,'$.contract_version')=3"
            ).fetchall()
            # The injected-transport collection is synthetic under the current lineage:
            # the forward_shadow draft receipts are not carried forward as forward proof,
            # and the new observations carry the witness's own time, never an older one.
            assert {mode for mode, _ in new} == {"synthetic"}
            assert {observed for _, observed in new} == {moment.isoformat()}
            assert journal.integrity(db)["classification"]["forecast_receipts"] == {
                "current": len(new),
                "legacy_draft": 22,
            }
        finally:
            store.close()


