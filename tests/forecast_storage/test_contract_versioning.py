def test_legacy_contract_two_cohort_is_evaluated_only_on_request(tmp_path):
    path = materialize("amended", tmp_path)
    cli(path, "forecast", "migrate", "--record-contract", "3")
    protocol = Protocol(dataset="demo-forward")
    as_of = datetime(2026, 9, 27, 23, 30, tzinfo=timezone.utc)
    clock = iter(
        datetime(2026, 9, 28, 0, 0, tzinfo=timezone.utc) + timedelta(seconds=n) for n in range(1000)
    )
    with writer_lock(path):
        store = Store(path, min_free_bytes=0)
        try:
            current = evaluate(
                store,
                protocol,
                view="forward-shadow",
                outcomes_as_of=as_of,
                clock=lambda: next(clock),
                monotonic=lambda: 0.0,
            )
            report = current["report"]
            assert report["record_contract"] == 3
            assert report["excluded_decisions"] == [
                {"id": 1, "contract": 2, "reason": "other_contract"}
            ]
            assert report["scores"]["paired"]["n"] == 0
            legacy = evaluate(
                store,
                protocol,
                view="forward-shadow",
                outcomes_as_of=as_of,
                record_contract=2,
                clock=lambda: next(clock),
                monotonic=lambda: 0.0,
            )
            assert legacy["report"]["record_contract"] == 2
            assert legacy["report"]["excluded_decisions"] == []
            assert legacy["report"]["scores"]["paired"]["n"] == 1  # the demo's one game
            from vader_intelligence.research import report as reports

            text = reports.text_report(store.db, current["evaluation_id"])
            assert "Record contract: 3" in text
            assert "Decisions outside this evaluation: contract 2 other_contract 1" in text
            assert "unrecorded (evaluated before D-001)" in reports.text_report(store.db, 1)
            for first, second in (
                (current["evaluation_id"], legacy["evaluation_id"]),
                (1, current["evaluation_id"]),
            ):
                with pytest.raises(ValueError, match="different record contracts"):
                    reports.compare(store.db, first, second)
        finally:
            store.close()


